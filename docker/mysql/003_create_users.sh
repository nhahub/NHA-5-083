#!/usr/bin/env bash
set -euo pipefail

# Provision least-privilege MySQL accounts after 001/002 schema creation.
MYSQL_PWD="${MYSQL_ROOT_PASSWORD}" mysql -u root "${MYSQL_DATABASE}" <<EOSQL
CREATE USER IF NOT EXISTS '${MYSQL_PIPELINE_USER}'@'%' IDENTIFIED BY '${MYSQL_PIPELINE_PASSWORD}';
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE VIEW, SHOW VIEW, CREATE, ALTER, DROP, INDEX
    ON \`${MYSQL_DATABASE}\`.* TO '${MYSQL_PIPELINE_USER}'@'%';

CREATE USER IF NOT EXISTS '${MYSQL_APP_USER}'@'%' IDENTIFIED BY '${MYSQL_APP_PASSWORD}';
GRANT SELECT ON \`${MYSQL_DATABASE}\`.* TO '${MYSQL_APP_USER}'@'%';

FLUSH PRIVILEGES;
EOSQL
